obj <- readRDS("../datos/datos_final_627.rds")
R <- obj$datos_originales[, c("Aroma","Flavor","Aftertaste","Acidity","Body","Balance","Cupper.Points","altitude_mean_meters")]
names(R) <- c("Aroma","Flavor","Aftertaste","Acidity","Body","Balance","Cupper.Points","Altitud")
S <- cov(R); Rc <- cor(R)
cat("n =", nrow(R), " tr(S) =", format(round(sum(diag(S)), 0), big.mark = "."), " det(S) =", format(det(S), scientific = TRUE, digits = 3), "\n")
cat("varianza log10:", round(log10(diag(S)), 2), "\n")
cat("cor min/max off-diag:", round(min(Rc[upper.tri(Rc)]), 2), round(max(Rc[upper.tri(Rc)]), 2), "\n")
png("figuras_var627/varianzas_627.png", width = 2400, height = 1100, res = 150, bg = "transparent")
par(mfrow = c(1, 2), mar = c(7, 4, 3, 1))
image(1:8, 1:8, t(Rc[8:1, ]), col = colorRampPalette(c("white", "#b03a3a", "#5a1010"))(30), zlim = c(0, 1), axes = FALSE, xlab = "", ylab = "")
axis(1, 1:8, colnames(Rc), las = 2, cex.axis = 0.8); axis(2, 1:8, rev(rownames(Rc)), las = 2, cex.axis = 0.8)
for (i in 1:8) for (j in 1:8) text(i, 9 - j, sprintf("%.2f", Rc[j, i]), cex = 0.7)
title("Matriz de correlaciones R (627 lotes)", cex.main = 1)
bp <- barplot(log10(diag(S)), names.arg = colnames(S), las = 2, col = "#8fbaa8", ylab = "log10(varianza)", main = "Varianza de cada variable (log10)", cex.names = 0.8)
dev.off()
